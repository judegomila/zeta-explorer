"""Degree-1 lab. (A) numerical check of the collapse lemma; (B) collapse statistics over prime conductors.
Run: python -I lab_dirichlet.py [QMAX]"""
import sys, json, math, cmath, random
import numpy as np

def primroot(q):
    n=q-1; fs=[]; m=n; d=2
    while d*d<=m:
        if m%d==0:
            fs.append(d)
            while m%d==0: m//=d
        d+=1
    if m>1: fs.append(m)
    g=2
    while any(pow(g,n//l,q)==1 for l in fs): g+=1
    return g

def chars(q):
    g=primroot(q); ind={}; x=1
    for k in range(q-1): ind[x]=k; x=x*g%q
    # chi_j(n)=exp(2 pi i j ind(n)/(q-1))
    return g,ind

# ---------- (A) lemma check ----------
def partA(q, parity, p, trials=200, seed=1):
    rng=np.random.default_rng(seed)
    g,ind=chars(q); n=q-1
    js=[j for j in range(n) if (j%2)==parity and j!=0]   # chi_j(-1)=(-1)^j ; drop principal
    X=np.array([[cmath.exp(2j*math.pi*j*ind[a]/n) for a in range(1,q)] for j in js])  # chars x residues
    res=list(range(1,q))
    H=[pow(p,k,q) for k in range(1,n+1)]; H=sorted(set(H))
    def resid(c):
        f=c@X   # f(a), a=1..q-1
        fa=lambda a: f[a-1]
        return np.array([fa(h*a%q)-fa(h)*fa(a) for h in H for a in res])
    out={'q':q,'parity':parity,'p':p,'nchars':len(js),'ord_p':len(H)}
    # fibres: characters grouped by restriction to <p>  (chi_j(p) = exp(2 pi i j ind p / n))
    fib={}
    for j in js: fib.setdefault(j*ind[p%q]%n,[]).append(j)
    out['fibre_sizes']=sorted(len(v) for v in fib.values())
    # in-fibre random combos: residual must vanish
    big=max(fib.values(),key=len); idx=[js.index(j) for j in big]
    worst=0
    for _ in range(20):
        c=np.zeros(len(js),complex); v=rng.normal(size=len(idx))+1j*rng.normal(size=len(idx)); v/=v.sum(); c[idx]=v
        worst=max(worst,np.abs(resid(c)).max())
    out['max_resid_in_fibre']=float(worst)
    # generic combos: residual nonzero
    c=rng.normal(size=len(js))+1j*rng.normal(size=len(js)); c/=c.sum()
    out['resid_generic']=float(np.abs(resid(c)).max())
    # independent nonlinear solve: Gauss-Newton from random starts on resid(c)=0, sum c = 1 ; classify supports
    def solve(c0):
        c=c0.copy()
        for it in range(200):
            r=np.concatenate([resid(c),[c.sum()-1]])
            if np.abs(r).max()<1e-13: break
            m=len(c); J=np.zeros((len(r),m),complex); eps=1e-7
            for k in range(m):
                d=np.zeros(m,complex); d[k]=eps
                J[:,k]=(np.concatenate([resid(c+d),[(c+d).sum()-1]])-r)/eps   # holomorphic in c
            step=np.linalg.lstsq(J,-r,rcond=None)[0]
            lam=1.0
            while lam>1e-6:
                r2=np.concatenate([resid(c+lam*step),[(c+lam*step).sum()-1]])
                if np.linalg.norm(r2)<np.linalg.norm(r): break
                lam/=2
            c=c+lam*step
        return c,np.abs(np.concatenate([resid(c),[c.sum()-1]])).max()
    conv=0; infib=0; supports={}
    for t in range(trials):
        c0=rng.normal(size=len(js))+1j*rng.normal(size=len(js)); c0/=c0.sum()
        c,err=solve(c0)
        if err<1e-10:
            conv+=1
            supp=[js[k] for k in range(len(js)) if abs(c[k])>1e-7]
            keys={j*ind[p%q]%n for j in supp}
            if len(keys)==1: infib+=1
            supports[len(supp)]=supports.get(len(supp),0)+1
    out.update(converged=conv,converged_in_single_fibre=infib,support_size_hist=supports,trials=trials)
    return out

# ---------- (B) collapse statistics ----------
def partB(QMAX, R=12):
    sieve=np.ones(QMAX+1,bool); sieve[:2]=False
    for i in range(2,int(QMAX**0.5)+1):
        if sieve[i]: sieve[i*i::i]=False
    primes=np.nonzero(sieve)[0].tolist()
    spf=list(range(QMAX+1))
    for i in range(2,int(QMAX**0.5)+1):
        if spf[i]==i:
            for k in range(i*i,QMAX+1,i):
                if spf[k]==k: spf[k]=i
    small=primes[:60]
    sum_free=[0.0]*(R+1); cnt_nontriv=[0]*(R+1); N=0
    collapse_hist={}; worst=(0,0,0); worst_ratio=(0,0,0); maxP0_by_decade={}
    for q in primes:
        if q<5: continue
        n=q-1; fac=[]; m=n
        while m>1:
            l=spf[m]; e=0
            while m%l==0: m//=l; e+=1
            fac.append((l,e))
        # v_l(index of <x>) for x: largest j<=e with x^(n/l^j)=1
        def vidx(x):
            out=[]
            for l,e in fac:
                j=0
                while j<e and pow(x,n//l**(j+1),q)==1: j+=1
                out.append(j)
            return out
        cur=vidx(q-1)      # subgroup generated by -1
        idx=1
        for (l,e),j in zip(fac,cur): idx*=l**j
        N+=1; r=0; P0=None; rstar=None
        free_r=[idx]
        for s in small:
            if s==q: continue
            if idx>1:
                v=vidx(s); cur=[min(a,b) for a,b in zip(cur,v)]
                idx=1
                for (l,e),j in zip(fac,cur): idx*=l**j
            r+=1
            if r<=R: free_r.append(idx)
            if idx==1 and P0 is None: P0=s; rstar=r
            if r>R and idx==1: break
        if P0 is None: raise RuntimeError(q)
        for r in range(R+1):
            sum_free[r]+=free_r[r]-1; cnt_nontriv[r]+=(free_r[r]>1)
        collapse_hist[rstar]=collapse_hist.get(rstar,0)+1
        if P0>worst[1]: worst=(q,P0,rstar)
        ratio=P0/math.log(q)**2
        if q>100 and ratio>worst_ratio[2]: worst_ratio=(q,P0,ratio)
        dec=int(math.log10(q)); maxP0_by_decade[dec]=max(maxP0_by_decade.get(dec,0),P0)
    pred=[0.5*2.0**(-r) for r in range(R+1)]
    return {'QMAX':QMAX,'n_prime_conductors':N,
            'mean_fibre_minus_1_after_r_primes':[x/N for x in sum_free],
            'frac_not_collapsed_after_r_primes':[c/N for c in cnt_nontriv],
            'heuristic_frac_l2_only':pred,
            'collapse_index_hist':dict(sorted(collapse_hist.items())),
            'largest_collapse_prime':{'q':worst[0],'P0':worst[1],'rstar':worst[2]},
            'max_P0_over_log2q':{'q':worst_ratio[0],'P0':worst_ratio[1],'ratio':worst_ratio[2]},
            'max_P0_by_decade':maxP0_by_decade}

if __name__=='__main__':
    QMAX=int(sys.argv[1]) if len(sys.argv)>1 else 10**6
    A=[partA(5,1,11),partA(5,1,2),partA(13,1,3),partA(13,1,5),partA(13,0,3),partA(17,1,2),partA(17,1,13,trials=100),partA(31,1,2,trials=60),partA(31,1,5,trials=60)]
    for a in A: print(json.dumps(a))
    B=partB(QMAX)
    print(json.dumps(B,indent=1))
    json.dump({'A':A,'B':B},open('lab_dirichlet.json','w'),indent=1)
