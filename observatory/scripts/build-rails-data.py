#!/usr/bin/env python3
"""Build dist/rails-data.js: tables that are too slow to form in the browser.

Run from the observatory directory, with mpmath available:

    python3 scripts/build-rails-data.py            # writes dist/rails-data.js

Contents
  V(a)      = (1/2) sum_n Lambda(n)^2 n^(-1-2a)                (time-delay variance / 4)
  v(a)      = (1/(2 pi^2)) sum_n Lambda(n)^2 / (n^(1+2a) log^2 n)   (prime jitter term)
  zeta(1+2a)
  the first 1000 zero ordinates of zeta (for the spacing statistics)

Methods (both avoid the slowly convergent sums over n):
  sum_n Lambda(n)^2 n^(-s) = sum_{K>=1} c(K) g(K s),  g = (log zeta)'',  c(K) = prod_{p | K} (1 - p)
  sum_n Lambda(n)^2 n^(-s) / log^2 n = sum_{r>=1} P(r s) / r^2,  P = prime zeta function
Each entry is checked against a direct sum over prime powers with an integral
tail where that sum converges fast enough (a >= 0.5). Values are rounded to 15
significant digits. Midpoint arithmetic at 40 digits; not interval-certified.
"""
import json, os, sys
from mpmath import mp, mpf, zeta, primezeta, pi, log, zetazero, nstr

mp.dps = 40
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'dist', 'rails-data.js')


def primes_upto(n):
    sieve = bytearray([1]) * (n + 1)
    sieve[0:2] = b'\x00\x00'
    for i in range(2, int(n ** 0.5) + 1):
        if sieve[i]:
            sieve[i * i::i] = bytearray(len(sieve[i * i::i]))
    return [i for i in range(n + 1) if sieve[i]]


PRIMES = primes_upto(400)


def c_coeff(K):
    c = 1
    for p in PRIMES:
        if p > K:
            break
        if K % p == 0:
            c *= 1 - p
    return c


def g(s):
    z = zeta(s)
    return zeta(s, derivative=2) / z - (zeta(s, derivative=1) / z) ** 2


def lambda2_series(s, kmax=260):
    total = mpf(0)
    for K in range(1, kmax + 1):
        term = c_coeff(K) * g(K * s)
        total += term
        if K > 8 and abs(term) < mpf(10) ** (-36):
            break
    return total


def V(a):
    return lambda2_series(1 + 2 * mpf(a if isinstance(a, str) else repr(a))) / 2


def v_jitter(a, rmax=400):
    s = 1 + 2 * mpf(repr(a))
    total = mpf(0)
    for r in range(1, rmax + 1):
        term = primezeta(r * s) / r ** 2
        total += term
        if r > 4 and abs(term) < mpf(10) ** (-36):
            break
    return total / (2 * pi ** 2)


def direct_V(a, N=200000):
    """Direct sum over prime powers n <= N plus the prime-number-theorem tail."""
    s = 1 + 2 * mpf(a)
    total = mpf(0)
    for p in primes_upto(N):
        lp, q = log(mpf(p)), p
        while q <= N:
            total += lp * lp * mpf(q) ** (-s)
            q *= p
    x = mpf(N)
    tail = x ** (-2 * mpf(a)) * (log(x) / (2 * a) + 1 / (4 * mpf(a) ** 2))
    return (total + tail) / 2


def grid():
    out = []
    out += [round(0.005 * k, 3) for k in range(1, 20)]          # 0.005 .. 0.095
    out += [round(0.01 * k, 2) for k in range(10, 50)]          # 0.10 .. 0.49
    out += [round(0.05 * k, 2) for k in range(10, 61)]          # 0.50 .. 3.00
    return out


def main():
    rows = []
    for a in grid():
        rows.append((a, V(a), v_jitter(a), zeta(1 + 2 * mpf(repr(a)))))
    # Independent check of a few entries.
    for a, ref in ((0.5, '0.40260491011420701475'), (1.0, '0.080242019551761946297')):
        val = V(a)
        assert abs(val - mpf(ref)) < mpf(10) ** (-19), (a, val)
        assert abs(direct_V(a) - val) < mpf(10) ** (-4), (a, direct_V(a), val)
    assert abs(V(0.01) - mpf('1249.2704311413671220')) < mpf(10) ** (-15)
    assert abs(v_jitter(1) - mpf('0.0090819039')) < mpf(10) ** (-9)
    assert abs(v_jitter(2) - mpf('0.0018241297')) < mpf(10) ** (-9)
    # Expansion constants V(a) = 1/(8a^2) + V0 + V1 a + ...
    V0 = mpf('-0.786575535662477613639890981443')
    V1 = mpf('6.02404097319776246715183527666')
    a = mpf('0.001')
    assert abs(V('0.001') - (1 / (8 * a * a) + V0 + V1 * a)) < mpf(10) ** (-4)

    zeros = [zetazero(n).imag for n in range(1, 1001)]

    f = lambda x: nstr(x, 15, strip_zeros=False)
    lines = [
        '/**',
        ' * Generated by scripts/build-rails-data.py (mpmath, 40 digits, rounded to 15).',
        ' * Do not edit by hand; rerun the script.',
        ' *',
        ' * RAILS_TABLE rows: [a, V(a), v(a), zeta(1+2a)] with',
        ' *   V(a) = (1/2) Σ Λ(n)² n^(−1−2a),   v(a) = (1/2π²) Σ Λ(n)² / (n^(1+2a) log² n).',
        ' * ZETA_ZEROS_1000: ordinates of the first 1000 zeros of ζ on the critical line.',
        ' */',
        'export const V_EXPANSION=Object.freeze({V0:-0.786575535662477614,V1:6.02404097319776});',
        'export const RAILS_TABLE=Object.freeze([',
    ]
    for a, va, vj, z in rows:
        lines.append('[%s,%s,%s,%s],' % (repr(a), f(va), f(vj), f(z)))
    lines.append(']);')
    lines.append('export const ZETA_ZEROS_1000=Object.freeze([')
    for i in range(0, 1000, 10):
        lines.append(','.join(nstr(z, 13, strip_zeros=False) for z in zeros[i:i + 10]) + ',')
    lines.append(']);')
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', os.path.normpath(OUT), os.path.getsize(OUT), 'bytes;', len(rows), 'rows')


if __name__ == '__main__':
    main()
