#!/usr/bin/env python3
"""gen_lean: write the Lean data module and the per-chunk `decide +kernel` files for one exported run.

usage: gen_lean.py EXPORT.json NAME CHUNK_STEPS
  EXPORT.json  output of export_f2.py / export_r78.py (kernels, floors, runs, U, q0, qb)
  NAME         Lean namespace / file stem (F2 or R78)
  CHUNK_STEPS  substeps per chunk file
Writes (relative to the package root):
  QrhLambda/Data/NAME.lean            tables, chunk run lists, boundary states, the Cert
  QrhLambda/Chunks/NAMECxx.lean       one `decide +kernel` theorem per chunk
  QrhLambda/NAMEChunks.lean           collects the chunk theorems into `∀ j < #chunks, chunkOK j`
The chain is re-simulated here with the same integer algorithm as QrhLambda/Checker.lean to obtain the
boundary states (the Lean kernel re-derives every one of them; nothing here is trusted).
"""
import sys, json, os
from fractions import Fraction as F

TWO96 = 2 ** 96


def qlit(x):
    x = F(x)
    assert x >= 0
    return f"mkQ {x.numerator} {x.denominator}"


def capof(r, M, v):
    a = r * r
    if 3 * a >= 1:
        return min(M, 2 / (1 + a))
    if (1 + a - v) ** 2 >= 4 * a * (1 + a):
        return min(M, 2 * (1 + a - v) / ((1 + a - v) ** 2 + 4 * a * v))
    return M


def horner(N, D):
    Fv, C = 1, 1
    for j in range(17, -1, -1):
        C = C * D * (j + 1)
        NF = N * Fv
        assert NF <= C
        Fv = C - NF
    return Fv, C


def step(kr, fl, P, Q):
    r, lam, M = F(kr['r']), F(kr['lam']), F(kr['M'])
    h, ell = F(fl['h']), F(fl['ell'])
    q = F(P, Q)
    v = q / (h * h)
    cap = capof(r, M, v)
    c = 2 * lam / h * (ell - cap / h)
    a, b = c.numerator, c.denominator
    Fv, C = horner(a, 512000 * b)
    A = P * a + 2 * b * Q
    tbc = 2 * b * Q * C
    den = Q * a * C
    return (TWO96 * (A * Fv - tbc) + den - 1) // den


def main():
    exp, name, chunk = sys.argv[1], sys.argv[2], int(sys.argv[3])
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    d = json.load(open(exp))
    kers, flrs, runs = d['kernels'], d['floors'], d['runs']
    srcs = sorted(set(f['src'] for f in flrs))
    sidx = {s: i for i, s in enumerate(srcs)}
    # expand runs into per-substep (fi, ki)
    seq = []
    for fi, ki, ln in runs:
        seq += [(fi, ki)] * ln
    K = len(seq) - 1                      # terminal substep index
    P0, Q0 = d['q0']
    # simulate substeps 0 .. K-1
    states = {}
    P, Q = P0, Q0
    for n in range(K):
        fi, ki = seq[n]
        P = step(kers[ki], flrs[fi], P, Q); Q = TWO96
        states[n + 1] = (P, Q)
    # chunks over substeps 1 .. K-1
    bounds = list(range(1, K, chunk)) + [K]
    chunks = []
    for a, b in zip(bounds[:-1], bounds[1:]):
        rl = []
        for n in range(a, b):
            fi, ki = seq[n]
            if rl and rl[-1][0] == fi and rl[-1][1] == ki:
                rl[-1][2] += 1
            else:
                rl.append([fi, ki, 1])
        chunks.append((rl, (a,) + states[a], (b,) + states[b]))
    L = []
    L.append(f"-- AUTO-GENERATED by scripts/gen_lean.py from {os.path.basename(exp)}; do not edit.")
    L.append(f"-- {d.get('description', '')}")
    L.append("import QrhLambda.Checker\n")
    L.append("set_option maxRecDepth 100000\n")
    L.append(f"namespace QrhLambda.{name}\n")
    L.append("/-- provenance tags of the floor table (index = `Flr.src`) -/")
    L.append("def srcNames : List String := [" + ", ".join(json.dumps(s) for s in srcs) + "]\n")
    L.append(f"/-- kernel table ({len(kers)} rows): `⟨r, λ, ρ, M⟩`; certificate files listed in `kernelCerts`. -/")
    L.append("def kers : List Ker := [")
    L.append(",\n".join(f"  ⟨{qlit(k['r'])}, {qlit(k['lam'])}, {qlit(k['rho'])}, {qlit(k['M'])}⟩" for k in kers))
    L.append("]\n")
    L.append("/-- certificate source of each kernel row -/")
    L.append("def kernelCerts : List String := [" + ", ".join(json.dumps(k['cert'].split('/mathexplorer/')[-1]) for k in kers) + "]\n")
    L.append("/-- raw source of each floor entry (file#cell.mode.field, or the admission key@file of an r2 floor) -/")
    L.append("def floorFiles : List String := [" + ", ".join(json.dumps(f.get('file', '?')) for f in flrs) + "]\n")
    L.append(f"/-- floor table ({len(flrs)} entries): `⟨cell, r, h, ℓ, src⟩` -/")
    L.append("def flrs : List Flr := [")
    L.append(",\n".join(f"  ⟨{f['cell']}, {qlit(f['r'])}, {qlit(f['h'])}, {qlit(f['ell'])}, {sidx[f['src']]}⟩" for f in flrs))
    L.append("]\n")
    for j, (rl, s0, s1) in enumerate(chunks):
        L.append(f"def chunk{j:02d} : Chunk := ⟨[" + ", ".join(f"({a}, {b}, {c})" for a, b, c in rl) + "],")
        L.append(f"  ⟨{s0[0]}, {s0[1]}, {s0[2]}⟩, ⟨{s1[0]}, {s1[1]}, {s1[2]}⟩⟩")
    L.append("")
    L.append("def chunks : List Chunk := [" + ", ".join(f"chunk{j:02d}" for j in range(len(chunks))) + "]\n")
    U = F(d['U'])
    fi0, ki0 = seq[0]; fiK, kiK = seq[K]
    qb = F(d['qb'])
    L.append(f"/-- the run certificate: start q0 = {P0}/{Q0}, {K + 1} substeps, terminal substep {K} -/")
    L.append("def cert : Cert where")
    L.append("  kers := kers")
    L.append("  flrs := flrs")
    L.append(f"  q0 := ⟨0, {P0}, {Q0}⟩")
    L.append(f"  first := ({fi0}, {ki0})")
    L.append("  chunks := chunks")
    L.append(f"  term := ({fiK}, {kiK})")
    L.append(f"  U := {qlit(U)}")
    L.append(f"  qb := {qlit(qb)}\n")
    L.append(f"end QrhLambda.{name}")
    open(os.path.join(root, f'QrhLambda/Data/{name}.lean'), 'w').write("\n".join(L) + "\n")
    # chunk files
    for j in range(len(chunks)):
        C = [f"-- AUTO-GENERATED by scripts/gen_lean.py; kernel-only check of chunk {j} of {name}",
             f"-- substeps {chunks[j][1][0]} .. {chunks[j][2][0] - 1}",
             f"import QrhLambda.Data.{name}\n",
             "set_option maxRecDepth 100000\n",
             f"namespace QrhLambda.{name}\n",
             f"theorem chunk{j:02d}_ok : cert.chunkOK {j} = true := by decide +kernel\n",
             f"end QrhLambda.{name}"]
        open(os.path.join(root, f'QrhLambda/Chunks/{name}C{j:02d}.lean'), 'w').write("\n".join(C) + "\n")
    # collector
    nC = len(chunks)
    M = [f"-- AUTO-GENERATED by scripts/gen_lean.py; collects the {nC} chunk checks of {name}"]
    M += ["import QrhLambda.Terminal11"] + [f"import QrhLambda.Chunks.{name}C{j:02d}" for j in range(nC)]
    M += ["", f"namespace QrhLambda.{name}", "",
          "theorem frame11_ok : cert.frame11 = true := by decide +kernel", "",
          f"theorem chunks_length : cert.chunks.length = {nC} := by decide +kernel", "",
          "theorem all_chunks_ok : ∀ j < cert.chunks.length, cert.chunkOK j = true := by",
          "  rw [chunks_length]",
          "  intro j hj",
          "  match j, hj with"]
    M += [f"  | {j}, _ => exact chunk{j:02d}_ok" for j in range(nC)]
    M += [f"  | k + {nC}, h => exact absurd h (by omega)", "", f"end QrhLambda.{name}"]
    open(os.path.join(root, f'QrhLambda/{name}Chunks.lean'), 'w').write("\n".join(M) + "\n")
    print(json.dumps(dict(name=name, substeps=K + 1, terminal=K, chunks=nC, kernels=len(kers), floors=len(flrs),
                          U=str(U), first=(fi0, ki0), term=(fiK, kiK), srcs=srcs)))


if __name__ == '__main__':
    main()
