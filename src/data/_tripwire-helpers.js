/**
 * Tripwire: accessor(row) is monotone across the array in the chosen
 * direction. Default 'increasing' means strict non-decreasing (next >= prev);
 * 'decreasing' means strict non-increasing (next <= prev). Use 'strict-
 * increasing' or 'strict-decreasing' for strict variants.
 *
 *   makeMonotoneTripwire('foo-step-monotone', ROWS, (r) => r.step,
 *                        'increasing')
 *
 * @param {string} id
 * @param {unknown[]} arr
 * @param {(row: unknown) => number} accessor
 * @param {'increasing'|'decreasing'|'strict-increasing'|'strict-decreasing'} [direction='increasing']
 * @param {string} [why]
 */
export function makeMonotoneTripwire(id, arr, accessor, direction, why) {
  const dir = direction || 'increasing';
  const reason =
    why ||
    'Sequence accessor(row) must be monotone (' + dir + ') across the array. ' +
      'A drift breaks the documented ordering claim.';
  return {
    id,
    why: reason,
    holds: () => {
      if (!_isArr(arr) || arr.length < 2) return false;
      let prev = _safeAccessor(accessor, arr[0]);
      if (!Number.isFinite(prev)) return false;
      for (let i = 1; i < arr.length; i++) {
        const cur = _safeAccessor(accessor, arr[i]);
        if (!Number.isFinite(cur)) return false;
        if (dir === 'increasing'         && !(cur >= prev)) return false;
        if (dir === 'decreasing'         && !(cur <= prev)) return false;
        if (dir === 'strict-increasing'  && !(cur >  prev)) return false;
        if (dir === 'strict-decreasing'  && !(cur <  prev)) return false;
        prev = cur;
      }
      return true;
    },
  };
}

/**
 * Tripwire: sum of accessor(row) over all rows equals expected, within
 * tolerance. tolerance defaults to 0 (exact equality, e.g. integer count
 * partitions). For floating-point comparisons pass a small positive tol.
 *
 *   makeSumEqualsTripwire('foo-count-sum-totals-100',
 *                         CATEGORY_ROWS, (r) => r.count, 100)
 *
 * @param {string} id
 * @param {unknown[]} arr
 * @param {(row: unknown) => number} accessor
 * @param {number} expected
 * @param {number} [tolerance=0]
 * @param {string} [why]
 */
export function makeSumEqualsTripwire(id, arr, accessor, expected, tolerance, why) {
  const tol = (typeof tolerance === 'number' && tolerance >= 0) ? tolerance : 0;
  const reason =
    why ||
    'Sum of accessor(row) over all rows must equal ' + expected +
      ' within tolerance ' + tol + '. A drift means the row partition no ' +
      'longer covers the documented total.';
  return {
    id,
    why: reason,
    holds: () => {
      if (!_isArr(arr) || arr.length === 0) return false;
      let s = 0;
      for (const row of arr) {
        const v = _safeAccessor(accessor, row);
        if (!Number.isFinite(v)) return false;
        s += v;
      }
      return Math.abs(s - expected) <= tol;
    },
  };
}

/**
 * Tripwire: a frozen string contains the given substring. Substring match
 * is case-sensitive by default; pass a RegExp instead of a string to use
 * regex semantics.
 *
 *   makeStringContainsTripwire('foo-verdict-mentions-pass',
 *                              FOO.verdict, 'pass')
 *
 * @param {string} id
 * @param {string} str
 * @param {string|RegExp} substring
 * @param {string} [why]
 */
export function makeStringContainsTripwire(id, str, substring, why) {
  const isRegex = substring instanceof RegExp;
  const label = isRegex ? substring.toString() : '"' + substring + '"';
  const reason =
    why ||
    'String under test must contain ' + label + '. A drift means the frozen ' +
      'document no longer matches the documented framing.';
  return {
    id,
    why: reason,
    holds: () => {
      if (typeof str !== 'string') return false;
      if (isRegex) return substring.test(str);
      return str.indexOf(substring) !== -1;
    },
  };
}

/**
 * Tripwire: a frozen object's field equals the expected value (===).
 * For deep / structural equality use a bespoke inline tripwire — this
 * helper only handles primitives / reference equality.
 *
 *   makeFrozenObjectTripwire('foo-discretizationN-is-200',
 *                            FOO.method, 'discretizationN', 200)
 *
 * @param {string} id
 * @param {object} obj
 * @param {string} fieldName
 * @param {unknown} expectedValue
 * @param {string} [why]
 */
export function makeFrozenObjectTripwire(id, obj, fieldName, expectedValue, why) {
  const reason =
    why ||
    'Frozen object field "' + fieldName + '" must equal expected value. A ' +
      'drift means the frozen record was overwritten or never synced.';
  return {
    id,
    why: reason,
    holds: () => {
      if (obj === null || typeof obj !== 'object') return false;
      return obj[fieldName] === expectedValue;
    },
  };
}

