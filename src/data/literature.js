export function getAllReferences() {
  return literature;
}

export function getByCategory(category) {
  return literature.filter(r => r.category === category);
}

export function getCategories() {
  const cats = new Set(literature.map(r => r.category));
  return [...cats];
}

export function searchReferences(query) {
  const q = query.toLowerCase();
  return literature.filter(r =>
    r.title.toLowerCase().includes(q) ||
    r.summary.toLowerCase().includes(q) ||
    r.tags.some(t => t.toLowerCase().includes(q)) ||
    r.authors.some(a => a.toLowerCase().includes(q)) ||
    (r.keyInsight && r.keyInsight.toLowerCase().includes(q))
  );
}

export function getById(id) {
  return literature.find(r => r.id === id);
}

export default literature;
