function emOneMinusU(u) {
  return Math.expm1(u) - u;
}

// imp-95402 parametric boundary at parameter u = (r - 1) x > 0.
function parametricBoundaryAtU(u) {
  const g = emOneMinusU(u);
  return { x: (u * u) / (2 * g), r: 1 + (2 * g) / u };
}

// imp-95377 implicit equation residual: e^((r-1)x) - (1 + (x/2)(r^2-1)).
function implicitResidual(x, r) {
  const lhs = Math.exp((r - 1) * x);
  const rhs = 1 + (x / 2) * (r * r - 1);
  return Math.abs(lhs - rhs) / rhs;
}

