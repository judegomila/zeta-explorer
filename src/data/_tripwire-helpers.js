// @module data/_tripwire-helpers
// imp-1281 -- META-HARNESS: reusable tripwire factory library.
//
// PURPOSE
// -------
// Subagent tickets routinely ship 5-10 build-time tripwires. The same handful
// of patterns recur across nearly every ticket:
//
//   * "this array must have exactly N rows"
//   * "every row in this array has field X"
//   * "every row's accessor(row) is <= some upper bound"
//   * "every row's accessor(row) is >= some lower bound"
//   * "the array is monotone (increasing / decreasing) in accessor"
//   * "the sum of accessor(row) equals expected total (within tolerance)"
//   * "a frozen string contains substring S"
//   * "a frozen object field equals expected value"
//
// Each handwritten tripwire that walks one of these patterns is 5-10 lines of
// boilerplate (id + why + 3-6 line holds closure). At 5-10 tripwires per
// ticket * many tickets per wave, the boilerplate ran to ~200 lines per wave.
//
// This module ships factories that emit standard-shape tripwires
//
//     { id: string, why: string, holds: () => boolean }
//
// from one-line invocations, and refactors imp-1240 / imp-1245 / imp-1258 to
// consume them as a proof-of-value (see those files' updated headers).
//
// API CONVENTIONS
// ---------------
// * Every factory takes `id` (string) as its FIRST parameter. The orchestrator
//   re-uses tripwire ids as stable cross-ticket handles; making id positional-
//   first prevents accidental reordering when refactoring inline → helper.
// * `why` is auto-generated by the factory but can be customized via the
//   trailing optional `why` argument when context-specific framing is needed.
// * Every factory returns a plain object { id, why, holds } — no class /
//   prototype magic, so the result is `JSON.stringify`-clean and inspectable.
// * `holds` is a thunk that returns a boolean. It captures the array / scalar
//   under test by closure; do NOT re-bind `this` inside holds.
// * Helpers do NOT validate input shape at call time — that is the tripwire
//   author's job. Helpers DO defensively guard against null / undefined input
//   inside holds so a missing import fires the tripwire rather than crashing
//   the assertion sweep.
//
// USAGE PATTERN
// -------------
//
//   import { makeRowCountTripwire } from './_tripwire-helpers.js';
//
//   export const FOO_ASSERTIONS = [
//     makeRowCountTripwire('foo-25-rows', FROZEN_ROWS, 25,
//       'The 5x5 sweep must produce exactly 25 rows.'),
//     // ... bespoke tripwires that don't fit any helper, inline as before
//   ];
//
// Each helper call is ONE line (or 2-3 with custom why) vs ~5-7 lines for the
// hand-rolled form.
//
// HONEST SCOPE
// ------------
// * These helpers cover the COMMON cases. Tripwires with cross-field logic,
//   multi-array correlation, or non-trivial regex semantics should stay inline.
//   The imp-1240 / imp-1245 / imp-1258 refactor leaves the bespoke tripwires
//   untouched and only replaces the patterns that map exactly.
// * Helper signatures are STABLE — changing the parameter order would silently
//   break every consumer (no compile-time check). The id-first convention is
//   permanent; subsequent params follow the natural reading order (array
//   first, then accessor / threshold / etc.).
// * Self-test sweep at the bottom of this file exercises each factory with
//   both passing and failing inputs. The TRIPWIRE_HELPERS_SELFTEST_ASSERTIONS
//   export is wired into scripts/run-assertions.mjs so any regression in a
//   helper fires before consumers' tripwires can become unreliable.

// ── Internal helpers (not exported) ────────────────────────────────────────

function _isArr(x) {
  return Array.isArray(x);
}

function _safeAccessor(accessor, row) {
  try {
    return accessor(row);
  } catch (_e) {
    return undefined;
  }
}

// ── Factories ──────────────────────────────────────────────────────────────

/**
 * Tripwire: an array has exactly the expected number of rows.
 *
 *   makeRowCountTripwire('foo-rows-25', FROZEN_ROWS, 25)
 *
 * @param {string} id
 * @param {unknown[]} arr  the array under test (captured by closure)
 * @param {number} expected  expected length
 * @param {string} [why]  optional override for the auto-generated rationale
 * @returns {{ id: string, why: string, holds: () => boolean }}
 */
export function makeRowCountTripwire(id, arr, expected, why) {
  const reason =
    why ||
    'Array length must equal ' + expected + '. A drift in row count means ' +
      'the sweep grid or freeze step dropped/duplicated rows.';
  return {
    id,
    why: reason,
    holds: () => _isArr(arr) && arr.length === expected,
  };
}

/**
 * Tripwire: every row in an array has the named field (non-undefined).
 *
 *   makeFieldPresenceTripwire('foo-rows-have-norm', FROZEN_ROWS, 'norm')
 *
 * @param {string} id
 * @param {unknown[]} arr
 * @param {string} fieldName
 * @param {string} [why]
 */
export function makeFieldPresenceTripwire(id, arr, fieldName, why) {
  const reason =
    why ||
    'Every row must carry the field "' + fieldName + '". A missing field ' +
      'means the freeze schema drifted from what consumers expect.';
  return {
    id,
    why: reason,
    holds: () =>
      _isArr(arr) &&
      arr.length > 0 &&
      arr.every((row) =>
        row !== null && typeof row === 'object' && row[fieldName] !== undefined,
      ),
  };
}

/**
 * Tripwire: every accessor(row) is <= bound (numeric).
 *
 *   makeAllBelowTripwire('foo-norms-le-1', FROZEN_ROWS, (r) => r.norm, 1)
 *
 * @param {string} id
 * @param {unknown[]} arr
 * @param {(row: unknown) => number} accessor
 * @param {number} bound
 * @param {string} [why]
 */
export function makeAllBelowTripwire(id, arr, accessor, bound, why) {
  const reason =
    why ||
    'Every row must satisfy accessor(row) <= ' + bound + '. A row above the ' +
      'bound means the frozen data is inconsistent with the documented verdict.';
  return {
    id,
    why: reason,
    holds: () => {
      if (!_isArr(arr) || arr.length === 0) return false;
      for (const row of arr) {
        const v = _safeAccessor(accessor, row);
        if (!Number.isFinite(v)) return false;
        if (!(v <= bound)) return false;
      }
      return true;
    },
  };
}

