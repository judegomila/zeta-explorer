/**
 * Riemann zeta function computation and related functions.
 * Implements the Dirichlet series, Euler product, and functional equation.
 */

import { getPrimes, primeFrequency } from './primes.js';

/**
 * Complex number arithmetic helpers
 */
export function cMul(a, b) {
  return [a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0]];
}

export function cDiv(a, b) {
  const d = b[0] * b[0] + b[1] * b[1];
  if (d < 1e-30) return [0, 0]; // division-by-zero protection
  return [(a[0] * b[0] + a[1] * b[1]) / d, (a[1] * b[0] - a[0] * b[1]) / d];
}

export function cAdd(a, b) {
  return [a[0] + b[0], a[1] + b[1]];
}

export function cSub(a, b) {
  return [a[0] - b[0], a[1] - b[1]];
}

export function cAbs(a) {
  return Math.sqrt(a[0] * a[0] + a[1] * a[1]);
}

export function cExp(a) {
  const r = Math.exp(a[0]);
  return [r * Math.cos(a[1]), r * Math.sin(a[1])];
}

export function cLog(a) {
  const r = cAbs(a);
  if (r < 1e-300) return [-690, Math.atan2(a[1], a[0])]; // log(1e-300) ≈ -690, avoid -Infinity
  return [Math.log(r), Math.atan2(a[1], a[0])];
}

export function cPow(base, exp) {
  if (cAbs(base) < 1e-300) return [0, 0];
  return cExp(cMul(exp, cLog(base)));
}

/**
 * Zeta via Dirichlet series (converges for Re(s) > 1)
 * zeta(s) = sum_{n=1}^{N} 1/n^s
 */
export function zetaDirichlet(s, N = 1000) {
  // Fast path: n^{-s} = n^{-σ} · e^{-it·log(n)} for real positive base n
  // Avoids cPow's generic cLog (atan2+sqrt) → cMul → cExp per term
  let re = 0, im = 0;
  const sigma = s[0], t = s[1];
  for (let n = 1; n <= N; n++) {
    const logN = Math.log(n);
    const mag = Math.exp(-sigma * logN);  // n^{-σ}
    const phase = -t * logN;              // -t·log(n)
    re += mag * Math.cos(phase);
    im += mag * Math.sin(phase);
  }
  return [re, im];
}

/**
 * Zeta via Euler product (product over primes)
 * zeta(s) = prod_p (1 - p^{-s})^{-1}
 */
export function zetaEulerProduct(s, numPrimes = 100) {
  const primes = getPrimes(numPrimes);
  let result = [1, 0];
  for (const p of primes) {
    // Fast path: p^{-s} = p^{-σ} · e^{-it·log(p)} for real positive base p
    // Avoids cPow's generic cLog (atan2+sqrt) → cMul → cExp per prime
    const logP = Math.log(p);
    const mag = Math.exp(-s[0] * logP);
    const phase = -s[1] * logP;
    const pmsRe = mag * Math.cos(phase);
    const pmsIm = mag * Math.sin(phase);
    const factor = [1 - pmsRe, -pmsIm];
    result = cDiv(result, factor);
  }
  return result;
}

/**
 * Individual Euler factor for prime p: 1/(1 - p^{-s})
 * This is the transfer function of one oscillator stage.
 */
export function eulerFactor(p, s) {
  // Fast path for real base: p^{-s} = p^{-σ} · e^{-it·log(p)}
  // Avoids cPow's generic cLog (atan2+sqrt) → cMul → cExp path
  const logP = Math.log(p);
  const mag = Math.exp(-s[0] * logP);      // p^{-σ}
  const phase = -s[1] * logP;              // -t·log(p)
  const pmsRe = mag * Math.cos(phase);
  const pmsIm = mag * Math.sin(phase);
  // 1/(1 - p^{-s})
  const denRe = 1 - pmsRe;
  const denIm = -pmsIm;
  const d = denRe * denRe + denIm * denIm;
  if (d < 1e-30) return [0, 0];
  return [denRe / d, -denIm / d];
}

/**
 * Partial Euler product up to the k-th prime
 */
export function partialEulerProduct(s, k) {
  const primes = getPrimes(k);
  let result = [1, 0];
  const stages = [{ prime: 1, factor: [1, 0], cumulative: [1, 0] }];
  for (let i = 0; i < primes.length; i++) {
    const p = primes[i];
    const f = eulerFactor(p, s);
    result = cMul(result, f);
    stages.push({
      prime: p,
      frequency: primeFrequency(p),
      factor: f,
      cumulative: [...result],
    });
  }
  return { value: result, stages };
}

/**
 * Riemann-Siegel Z function (approximation for visualizing on critical line)
 * Z(t) = exp(i*theta(t)) * zeta(1/2 + it)
 * where theta(t) is the Riemann-Siegel theta function
 */
export function riemannSiegelTheta(t) {
  // theta(t) ≈ t/2 * log(t/(2*pi)) - t/2 - pi/8 + ...
  return (t / 2) * Math.log(t / (2 * Math.PI)) - t / 2 - Math.PI / 8
    + 1 / (48 * t) + 7 / (5760 * t * t * t);
}

export function riemannSiegelZ(t) {
  if (t < 2 * Math.PI) return 0; // need N = floor(sqrt(t/2π)) >= 1
  const tau = Math.sqrt(t / (2 * Math.PI));
  const N = Math.floor(tau);
  const p = tau - N; // fractional part for correction term
  const theta = riemannSiegelTheta(t);
  let sum = 0;
  for (let n = 1; n <= N; n++) {
    sum += Math.cos(theta - t * Math.log(n)) / Math.sqrt(n);
  }
  sum *= 2;
  // C_0 correction term: improves accuracy from O(t^{-1/4}) to O(t^{-3/4})
  // Guard removable singularities at p=1/4 and p=3/4 where both numerator
  // and denominator vanish; by L'Hôpital / Taylor expansion the limit is 1/2.
  const cosDen = Math.cos(2 * Math.PI * p);
  const C0 = Math.abs(cosDen) < 1e-8
    ? 0.5
    : Math.cos(2 * Math.PI * (p * p - p - 1 / 16)) / cosDen;
  sum += Math.pow(t / (2 * Math.PI), -0.25) * (N % 2 === 0 ? -1 : 1) * C0;
  return sum;
}

