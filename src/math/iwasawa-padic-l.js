  for (const p of [2, 3, 5, 7]) {
    KLvalues[`p=${p}`] = [];
    for (let n = 2; n <= 16; n += 2) {
      const kl = kubotaLeopoldt(p, n, B);
      KLvalues[`p=${p}`].push({
        n,
        'zeta(1-n)': +zetaAtNegInt(n, B).toFixed(6),
        '(1-p^{n-1})*zeta(1-n)': +kl.toFixed(6),
      });
    }
  }

