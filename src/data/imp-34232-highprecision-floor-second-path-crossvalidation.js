const TWO_PI = 2 * Math.PI;
const E_TRUNC = 3.06e-5; // N-independent fixed strip (imp-2631/imp-33582/imp-33620/imp-33773)
const A1_TRAP = 2.37e-4;
const GRONWALL = Math.exp(1.0 * A1_TRAP); // matches imp-34168/imp-34106/imp-34044 exactly

// SECOND PATH (a): assemble the three energy channels from source, independently of the imp-34168
// parts() helper. fracColl = E_coll / E_N is the sigma of both modules.
function channels(N) {
  const T0 = effectiveHeightForN(N);
  const logT0 = Math.log(T0);
  const cFlow = (Math.log(T0 / TWO_PI) + 1) / TWO_PI; // imp-398 pinned prefactor
  const eFlow = cFlow * (logT0 / T0) * GRONWALL;
  const eColl = C_C_PINNED * Math.sqrt(logT0 / N); // GUE-conditional (C_H)
  const eTot = E_TRUNC + eFlow + eColl;
  return { eColl, fracColl: eColl / eTot };
}

// SECOND PATH (b): STABLE p_sigma -- mean-centred OLS of ln(fracColl) vs ln N, index-enumerated grid
// (d = dLo + i/per, distinct from the imp-34168 accumulated d += step loop).
function pSigma(loN, hiN, per = 4) {
  const dLo = Math.log10(loN);
  const dHi = Math.log10(hiN);
  const xs = [];
  const ys = [];
  for (let i = 0; ; i++) {
    const d = dLo + i / per;
    if (d > dHi + 1e-9) break;
    const N = Math.pow(10, d);
    xs.push(Math.log(N));
    ys.push(Math.log(channels(N).fracColl));
  }
  const n = xs.length;
  const mx = xs.reduce((a, b) => a + b, 0) / n;
  const my = ys.reduce((a, b) => a + b, 0) / n;
  let sxx = 0;
  let sxy = 0;
  for (let i = 0; i < n; i++) {
    sxx += (xs[i] - mx) ** 2;
    sxy += (xs[i] - mx) * (ys[i] - my);
  }
  return -sxy / sxx;
}

// Two algebraically-identical E_coll log-log slope forms (probed in Y2). RATIO is the imp-34168 form.
function pEcollRatio(loN, hiN) {
  return -Math.log(channels(hiN).eColl / channels(loN).eColl) / Math.log(hiN / loN);
}
function pEcollDifference(loN, hiN) {
  return -(Math.log(channels(hiN).eColl) - Math.log(channels(loN).eColl)) / (Math.log(hiN) - Math.log(loN));
}

// resid_exp(k) over window [10^k, 10^(k+1)] under a supplied E_coll slope form.
function residExp(k, pEcollFn) {
  const lo = Math.pow(10, k);
  const hi = Math.pow(10, k + 1);
  return pEcollFn(lo, hi) * (1 - channels(hi).fracColl) - pSigma(lo, hi);
}

// SECOND PATH (d): independent ternary re-location of the continuum peak on the supplied slope form.
function ternaryPeak(pEcollFn, lo = 8.0, hi = 9.5, iters = 300) {
  for (let i = 0; i < iters; i++) {
    const m1 = lo + (hi - lo) / 3;
    const m2 = hi - (hi - lo) / 3;
    if (residExp(m1, pEcollFn) < residExp(m2, pEcollFn)) lo = m1;
    else hi = m2;
  }
  return (lo + hi) / 2;
}

const ORIGIN = 6;
const WIN_LO = 8.7; // independent peak-bracketing window (imp-34168 used [8.6, 9.05])
const WIN_HI = 8.95;

// SECOND PATH (c): discrete argmax on the 6 + j*step grid, rounded to `decimals` (imp-34168 uses 12).
function argmaxWindowed(exponent, pEcollFn, decimals) {
  const step = 1 / Math.pow(2, exponent);
  const jLo = Math.ceil((WIN_LO - ORIGIN) / step);
  const jHi = Math.floor((WIN_HI - ORIGIN) / step);
  let bestK = ORIGIN + jLo * step;
  let bestV = -Infinity;
  for (let j = jLo; j <= jHi; j++) {
    const kk = +(ORIGIN + j * step).toFixed(decimals);
    const v = residExp(kk, pEcollFn);
    if (v > bestV) {
      bestV = v;
      bestK = kk;
    }
  }
  return { k: bestK, step };
}

// The stored 10-sig-fig phase anchor is reused verbatim from imp-34168 (a fixed input).
const K_TRUE_STORED = IMP34168_DOUBLING_MAP_HIGHPRECISION_KSTAR_FLOOR.storedKTrueHighPrecision; // 8.8210915879
const PHASE = K_TRUE_STORED - ORIGIN;
const REFLECTION_LO = 0.25; // frac in (1/4, 3/4) => the doubling crosses 1/2 => descent predicted at e+1
const REFLECTION_HI = 0.75;
const LADDER_EXPONENTS = [15, 16, 17, 18, 19, 20, 21, 22];

// SECOND PATH (e): regenerate the doubling-map orbit frac(2^e (k_true - 6)) by ITERATING the Bernoulli
// doubling map from frac(k_true - 6), an independent implementation of the transition predicate.
function doublingMapFracByExponent(maxExponent) {
  const byE = {};
  let f = PHASE - Math.floor(PHASE);
  for (let e = 0; e <= maxExponent; e++) {
    byE[e] = f;
    f = (2 * f) % 1;
  }
  return byE;
}
const FRAC_BY_E = doublingMapFracByExponent(23);

// Run the imp-34168 ladder machinery, phasing on the stored anchor with a given slope form and grid
// rounding. Returns rungs, transitions, first-departure exponent and max relative deviation.
function runLadder(pEcollFn, decimals) {
  const rungs = LADDER_EXPONENTS.map((exponent) => {
    const a = argmaxWindowed(exponent, pEcollFn, decimals);
    const gap = Math.abs(a.k - K_TRUE_STORED);
    const scaled = PHASE / a.step;
    const gridFrac = scaled - Math.floor(scaled);
    const saw = Math.min(gridFrac, 1 - gridFrac) * a.step;
    const frac = FRAC_BY_E[exponent];
    const relDeviation = gap > 0 ? Math.abs(saw - gap) / gap : 0;
    return {
      exponent,
      argmaxK: +a.k.toFixed(12),
      gap: +gap.toExponential(4),
      frac: +frac.toFixed(6),
      inReflectionBand: frac > REFLECTION_LO && frac < REFLECTION_HI,
      sawtoothPredicted: +saw.toExponential(4),
      relDeviationFromClosedForm: +relDeviation.toExponential(4),
    };
  });
  const transitions = [];
  for (let i = 1; i < rungs.length; i++) {
    const prev = rungs[i - 1];
    const cur = rungs[i];
    const realigned = cur.gap < prev.gap - 1e-18;
    transitions.push({
      toExponent: cur.exponent,
      realigned,
      predictedByPrevPhase: prev.inReflectionBand,
      rulePredictionCorrect: realigned === prev.inReflectionBand,
    });
  }
  const firstDeparture = transitions.find((t) => !t.rulePredictionCorrect) || null;
  const maxRelDeviation = rungs.reduce((m, r) => Math.max(m, r.relDeviationFromClosedForm), 0);
  return {
    rungs,
    transitions,
    firstDepartureExponent: firstDeparture ? firstDeparture.toExponent : null,
    allTransitionsCorrect: transitions.every((t) => t.rulePredictionCorrect),
    maxRelDeviation: +maxRelDeviation.toExponential(4),
  };
}

