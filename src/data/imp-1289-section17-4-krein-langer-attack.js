//             4th closure route for ‖V_{a,Φ}‖ ≤ 1.
//
// MOTIVATION
// ----------
// Paper §17 (twin_ladder_consolidated_v52.pdf, blaschke-ghosts-section.js)
// introduces Blaschke ghosts B_a^+ and the shifted scattering ratio
//   R_a(w) = R̃_a(w) / B_a^+(w),
// placing R_a in the generalized Schur class S^κ (Krein-Langer 1973/1977).
// §17.4 states the load-bearing identity
//
//     ind_-(K_{R_a})  =  #{ λ : X(λ) = 0, Re(λ) > a },   counted with multiplicity
//
// where ind_- is the Pontryagin negative-square count of the (indefinite)
// Schur reproducing kernel K_{R_a}(z, w) = (1 - R_a(z) R_a(w̄)) / (z + w̄).
//
// imp-1232 audited Conj 17.3 (B_a^+ ≡ 1) as SUBSUMED-BY-RH; the §17.4
// identity itself was used as a load-bearing reference but never directly
// opened as an INDEPENDENT closure route for ‖V_{a,Φ}‖ ≤ 1. imp-1258
// collapses §15-27 to that single operator-norm bound; §17.4 cites
// Krein-Langer informally inside the structural chain. This ticket asks:
// does the Krein-Langer S^κ class with κ = 0 add a 4th INDEPENDENT route
// alongside imp-1267 (HS), imp-1287 (Wiener-Hopf), and imp-1266 (Mellin,
// eliminated)?
//
// PRECISE §17.4 STATEMENT (Krein-Langer / Pontryagin form)
// --------------------------------------------------------
// (As quoted in blaschke-ghosts-section.js / paper §17.4.)
//
//   Claim (Krein-Langer 1973/77 applied to R_a):
//     R_a = R̃_a / B_a^+ lies in the generalized Schur class S^κ, where
//     κ = κ(a) is the integer Pontryagin index. The Pontryagin index equals
//     the number of negative squares of the indefinite Schur kernel:
//
//         ind_-( K_{R_a} )  =  κ(a)  =  #{ λ : X(λ) = 0, Re(λ) > a },
//
//     with multiplicity. κ = 0 ⇔ R_a ∈ Schur ⇔ B_a^+ ≡ 1 ⇔ no off-critical
//     zeros with horizontal displacement exceeding a.
//
// KREIN-LANGER S^κ THEORY SUMMARY (training-time recall)
// ------------------------------------------------------
// Krein-Langer (1973, "Über die verallgemeinerten Resolventen…"; 1977,
// "Über einige Fortsetzungsprobleme…"):
//
//   * S^κ := {meromorphic S in C_+ : K_S has exactly κ negative squares}.
//   * S^0 = ordinary Schur class (‖S‖_∞ ≤ 1 in C_+).
//   * For S ∈ S^κ there is a unique Krein-Langer factorization
//
//         S(z) = S_0(z) · ∏_{j=1}^{κ} b_{α_j}(z)^{-1}
//
//     where S_0 ∈ S^0 and b_α(z) = (z - α)/(z + ᾱ) is a Blaschke factor
//     with α in C_+. The κ inverse-Blaschke factors carry exactly κ
//     negative squares (one per pole α_j ∈ C_+ of S).
//
//   * Pontryagin's theorem: κ = dim of the maximal negative subspace of the
//     Pontryagin space Π_κ generated by K_S. Equivalently, κ = number of
//     poles of S in C_+ (counted with multiplicity).
//
//   * de Branges 1968 (Hilbert Spaces of Entire Functions) develops the
//     positive case S^0 from a different angle: K_S ⪰ 0 ⇔ Hermite-Biehler
//     ⇔ existence of the de Branges space H(E). The two theories agree on
//     S^0; Krein-Langer EXTENDS to κ ≥ 1.
//
// APPLICATION TO V_{a,Φ}
// ----------------------
// We want: does Krein-Langer give a 4th independent route to ‖V_{a,Φ}‖ ≤ 1?
//
// The §27 paper chain (imp-1219, imp-1258) gives the equivalence
//
//     ‖V_{a,Φ}‖ ≤ 1  ⇔  [[I, V], [V*, I]] ⪰ 0  ⇔  K_a ⪰ 0
//                   ⇔  E_a is Hermite-Biehler  ⇔  CDB-Exist.
//
// So we need: does Krein-Langer give a route to K_a ⪰ 0 (i.e., ind_- = 0)
// not passing through the de Branges H(E_a) machinery already used in the
// imp-1258 chain (step 4: K_a ⪰ 0 ⇔ E_a HB via de Branges 1968 Thm 23)?
//
// Two sub-questions:
//
//   (Q1) Is the κ = 0 case of the Krein-Langer S^κ theory the SAME object as
//        the de Branges H(E_a) positivity statement?
//
//   (Q2) If yes (Q1 = yes), does Krein-Langer give a PROOF of κ = 0 via a
//        path INDEPENDENT of the de Branges chain?
//
// ANSWER (Q1)
// -----------
// YES — the κ = 0 specialization of the Krein-Langer S^κ class is the
// ordinary Schur class S^0, which (via the standard Cayley transform between
// half-plane Schur class and the Hermite-Biehler condition; see de Branges
// 1968 §1) is EQUIVALENT to "E_a is Hermite-Biehler / K_a ⪰ 0". The two
// theories produce the SAME positivity statement in the κ = 0 specialization.
//
// Concretely:
//
//   Krein-Langer (κ = 0): R_a ∈ S^0 ⇔ ind_-(K_{R_a}) = 0
//                                  ⇔ K_{R_a} ⪰ 0
//                                  ⇔ R_a is Schur in C_+.
//
//   de Branges 1968 Thm 23: K_E ⪰ 0 ⇔ E is Hermite-Biehler.
//
// The Schur ratio R_a is built from E_a by R_a(w) = E_a^#(z(w))/E_a(z(w)),
// w = Cayley(z); R_a ∈ S^0 ⇔ E_a HB. So the κ = 0 specialization recovers
// the de Branges H(E_a) class.
//
// (κ = 0) Krein-Langer  ⇔  de Branges 1968 K_E ⪰ 0  ⇔  E_a HB
//
// is an EQUIVALENCE, not an inclusion. So the Krein-Langer route does NOT
// produce a positivity statement that the de Branges chain does not already
// produce.
//
// ANSWER (Q2)
// -----------
// The κ = 0 PROOF in Krein-Langer is the rank-one Schur algorithm + the
// Pontryagin-space dimension count. To PROVE κ = 0 directly requires:
//
//   (a) show R_a has no poles in C_+, OR
//   (b) show K_{R_a} has no negative subspace.
//
// Both routes are EQUIVALENT TO the original conjecture (Conj 17.3:
// B_a^+ ≡ 1, which imp-1232 audited as SUBSUMED-BY-RH). The Krein-Langer
// framework re-formulates the problem in Pontryagin-space language but does
// not supply NEW information about the location of zeros of X(λ) = ξ(1/2 + λ).
//
// In particular, Krein-Langer does NOT give:
//
//   * A Φ-side input (no Volterra bound, no kernel estimate).
//   * A growth-rate estimate (no sinh / cosh / Laplace bound).
//   * A measure-domination identity (no µ_pass ⪰ ν).
//
// All three would be REQUIRED for an independent route, and the imp-1267
// (HS) and imp-1287 (WH) routes get them from the Φ-side definition of V.
// Krein-Langer is a PACKAGING theorem: it tells you "this is the right
// language to count negative squares", but the COUNT itself reduces to the
// off-critical zero count of X, which is RH.
//
// COMPARISON WITH THE THREE OTHER ROUTES
// --------------------------------------
//
//   imp-1267 (HS, route 1)  : Φ-side analytical bound ‖V‖_op ≤ √(I_0 J_a),
//                             closed-form, closes a ∈ (0, ~2] (extended to
//                             a ∈ (0, ~37.66] by imp-1260 exact-HS).
//                             INDEPENDENT of zeros of X.
//
//   imp-1287 (WH, route 4)  : Wiener-Hopf factorization of the §27 Laplace
//                             symbol a/(z² - a²), closes a ≥ 1 (conjectural
//                             status: prepared by imp-1266 closure, not yet
//                             rigorously delivered). INDEPENDENT of zeros.
//
//   imp-1266 (Mellin)       : ELIMINATED at step 0 (V is not multiplicative
//                             convolution; Mellin of sinh diverges).
//
//   imp-1289 (Krein-Langer) : Packaging theorem in Pontryagin-space language.
//                             κ = 0 specialization recovers the de Branges
//                             H(E_a) ⇔ K_a ⪰ 0 ⇔ ‖V‖ ≤ 1 chain ALREADY USED
//                             in imp-1258. No NEW Φ-side input. REDUCES to
//                             RH (Conj 17.3 SUBSUMED-BY-RH per imp-1232).
//
// VERDICT
// -------
// recovers-de-branges-not-new.
//
// The Krein-Langer S^κ class with κ = 0 is EQUIVALENT to (not strictly
// stronger or weaker than) the de Branges H(E_a) Hermite-Biehler condition.
