def file_hash(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


@functools.cache
def divisors(n: int) -> tuple[int, ...]:
    small = []
    large = []
    for d in range(1, math.isqrt(n) + 1):
        if n % d == 0:
            small.append(d)
            if d * d != n:
                large.append(n // d)
    return tuple(small + list(reversed(large)))


@functools.cache
def von_mangoldt(n: int) -> float:
    if n < 2:
        return 0.0
    for p in range(2, n + 1):
        if any(p % q == 0 for q in range(2, int(math.sqrt(p)) + 1)):
            continue
        power = p
        while power < n:
            power *= p
        if power == n:
            return math.log(p)
    return 0.0


def omega(cutoff: int, m: int) -> float:
    return max(0.0, 1.0 - m / (cutoff + 1.0))


def ell(cutoff: int, n_total: int) -> float:
    return sum(
        von_mangoldt(n) * omega(cutoff, n_total // n)
        for n in divisors(n_total)
    )


def unrestricted(cutoff: int, n_total: int) -> float:
    total = 0.0
    for n in divisors(n_total):
        q = n_total // n
        total += von_mangoldt(n) * sum(
            omega(cutoff, m) * omega(cutoff, q // m)
            for m in divisors(q)
        )
    return total


def both_miss_center(cutoff: int, n_total: int) -> float:
    total = 0.0
    for n in divisors(n_total):
        q = n_total // n
        total += von_mangoldt(n) * sum(
            omega(cutoff, m) * omega(cutoff, q // m)
            for m in divisors(q)
            if m >= 2 and q // m >= 2
        )
    return total


def center_coefficient(cutoff: int, n_total: int) -> float:
    w1 = omega(cutoff, 1)
    return (
        2.0 * w1 * ell(cutoff, n_total)
        - w1 * w1 * von_mangoldt(n_total)
    )


def euler_maclaurin_zeta(s_value: float, cutoff: int = 20000) -> float:
    """Numerical zeta(s), s>1, with two Euler--Maclaurin corrections."""
    partial = math.fsum(n ** (-s_value) for n in range(1, cutoff))
    tail = (
        cutoff ** (1.0 - s_value) / (s_value - 1.0)
        + 0.5 * cutoff ** (-s_value)
        + (s_value / 12.0) * cutoff ** (-s_value - 1.0)
        - (s_value * (s_value + 1.0) * (s_value + 2.0) / 720.0)
        * cutoff ** (-s_value - 3.0)
    )
    return partial + tail


class FiniteFejerPostCoreQuantifierTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.text = NOTE.read_text(encoding="utf-8")

    def test_note_and_dependencies_are_hash_pinned(self) -> None:
        self.assertEqual(file_hash(NOTE), NOTE_HASH)
        for relative, expected in PROTECTED_HASHES.items():
            self.assertEqual(file_hash(ROOT / relative), expected, relative)

    def test_locked_schedule_is_odd_and_nonintegral(self) -> None:
        self.assertIn(r"p\geq5\text{ odd}", self.text)
        self.assertIn(r"A=\lambda^2={p^2\over4}\notin\mathbb Z", self.text)
        for p_value in range(5, 100, 2):
            self.assertEqual((p_value * p_value) % 4, 1)

    def test_claim_boundary_and_correct_quantifier_are_literal(self) -> None:
        for token in (
            "cannot be the scalar hypothesis",
            "limsup_{M\\to\\infty}",
            "variable operator generated by `C_M(N)`",
            "does not make `C_M` diagonal or positive",
            "P0_INVALIDATED",
        ):
            self.assertIn(token, self.text)

    def test_weighted_center_inclusion_exclusion(self) -> None:
        for cutoff in (1, 2, 5, 20, 100):
            for n_total in range(7, 81):
                left = unrestricted(cutoff, n_total) - both_miss_center(
                    cutoff, n_total
                )
                w1 = omega(cutoff, 1)
                right = (
                    2.0 * w1 * ell(cutoff, n_total)
                    - w1 * w1 * von_mangoldt(n_total)
                )
                self.assertAlmostEqual(left, right, places=12)

    def test_cutoff_one_has_no_unweighted_constant_core(self) -> None:
        for n_total in range(2, 100):
            w1 = omega(1, 1)
            coefficient = (
                2.0 * w1 * ell(1, n_total)
                - w1 * w1 * von_mangoldt(n_total)
            )
            self.assertAlmostEqual(
                coefficient, von_mangoldt(n_total) / 4.0, places=12
            )

    def test_midpoint_half_row(self) -> None:
        cutoff = 30
        n_total = 24
        # Choose a nonintegral A with N < 2A, as on the locked schedule.
        a_value = 49.0 / 4.0
        self.assertLess(n_total, 2.0 * a_value)
        interior = both_miss_center(cutoff, n_total)
        boundary_layer = omega(cutoff, 1) * sum(
            von_mangoldt(n) * omega(cutoff, n_total // n)
            for n in divisors(n_total)
            if n < a_value
        )
        midpoint_b = interior + 0.5 * boundary_layer
        c_m = unrestricted(cutoff, n_total) - interior
        self.assertAlmostEqual(
            unrestricted(cutoff, n_total) - midpoint_b,
            c_m - 0.5 * boundary_layer,
            places=12,
        )
        expected_layer = omega(cutoff, 1) * (
            ell(cutoff, n_total)
            - omega(cutoff, 1) * von_mangoldt(n_total)
        )
        self.assertAlmostEqual(boundary_layer, expected_layer, places=12)

    def test_exact_linear_weight_mismatch(self) -> None:
        for n_total in range(2, 80):
            cutoff = n_total + 17
            t_value = cutoff + 1.0
            s_value = n_total * sum(
                von_mangoldt(n) / n for n in divisors(n_total)
            )
            w1 = omega(cutoff, 1)
            c_m = (
                2.0 * w1 * ell(cutoff, n_total)
                - w1 * w1 * von_mangoldt(n_total)
            )
            c_infinity = 2.0 * math.log(n_total) - von_mangoldt(n_total)
            mismatch = (
                (-2.0 * math.log(n_total) - 2.0 * s_value
                 + 2.0 * von_mangoldt(n_total)) / t_value
                + (2.0 * s_value - von_mangoldt(n_total)) / t_value**2
            )
            self.assertAlmostEqual(c_m - c_infinity, mismatch, places=12)

    def test_center_rate_is_numerically_uniform(self) -> None:
        # This checks the dimensionless constant in |C_M-C_inf|=O(AL/M)
        # on locked center collars, rather than only matching a prose token.
        for p_value in range(5, 52, 2):
            a_value = p_value * p_value / 4.0
            l_value = math.log(a_value)
            cutoff = max(
                math.ceil(4.0 * a_value),
                math.ceil(a_value * l_value * l_value),
            )
            for n_total in range(math.floor(a_value) + 1, math.ceil(4.0 * a_value)):
                mismatch = abs(
                    center_coefficient(cutoff, n_total)
                    - (2.0 * math.log(n_total) - von_mangoldt(n_total))
                )
                scaled = mismatch * cutoff / (a_value * l_value)
                self.assertLess(scaled, 10.0)

    def test_step_jump_has_only_one_gap_power(self) -> None:
        split = 0.5
        scaled = []
        for odd_k in (1, 3, 9, 27):
            delta = 2.0 * math.pi * odd_k
            integral = (
                cmath.exp(1j * delta)
                - cmath.exp(1j * delta * split)
            ) / (1j * delta)
            self.assertAlmostEqual(abs(integral), 2.0 / delta, places=12)
            scaled.append(delta * delta * abs(integral))
        self.assertTrue(all(b > a for a, b in zip(scaled, scaled[1:])))

    def test_stieltjes_gate_is_fail_closed(self) -> None:
        for token in (
            "Dq=q_1(y)\\,dy+\\nu",
            "variation of `nu` alone supplies no second denominator",
            "direct gap-weighted operator estimate",
            "4\\zeta(1+\\eta)\\over3\\pi",
            "short-interval Brun--Titchmarsh",
            "hard-end Hankel--Christoffel--Darboux scalar error",
        ):
            self.assertIn(token, self.text)

    def test_gap_decay_row_sum_constant(self) -> None:
        for eta in (0.25, 0.5, 1.0):
            zeta_value = euler_maclaurin_zeta(1.0 + eta)
            asserted_constant = 4.0 * zeta_value / (3.0 * math.pi)
            finite_row_sum = (
                4.0
                / (3.0 * math.pi)
                * math.fsum(q ** (-1.0 - eta) for q in range(1, 10001))
            )
            self.assertLess(finite_row_sum, asserted_constant)

    def test_matrix_tex_has_no_dropped_backslash(self) -> None:
        self.assertNotIn("{widehat\\nu", self.text)
        self.assertNotIn("\\left[{\\widehat", self.text)
        self.assertIn("\\left[\\widehat\\nu", self.text)


