// Cache for Borwein acceleration weights, keyed by n
const _borweinWeightCache = new Map();

function getBorweinWeights(n) {
  if (_borweinWeightCache.has(n)) return _borweinWeightCache.get(n);
  const e = new Float64Array(n + 1);
  e[n] = 0;
  let binom = 1; // starts as C(n, n) = 1
  for (let k = n - 1; k >= 0; k--) {
    e[k] = e[k + 1] + binom / Math.pow(2, n);
    binom = binom * (k + 1) / (n - k);
  }
  _borweinWeightCache.set(n, e);
  return e;
}

/**
 * Compute zeta on the critical strip using Borwein acceleration.
 * Uses the Dirichlet eta function with Knopp-Hasse binomial acceleration:
 *   eta(s) ≈ Σ_{k=0}^{n} e_k · (-1)^k · (k+1)^{-s}
 * where e_k = Σ_{j=k+1}^{n} C(n,j) / 2^n are the acceleration weights.
 * Convergence: O(2^{-n}), giving ~15 digits with n=50.
 */
export function zetaCriticalStrip(s, N = 50) {
  const n = Math.min(N, 60); // cap at 60 to avoid overflow in binomial coefficients

  // Acceleration weights are s-independent; cache and reuse across calls
  const e = getBorweinWeights(n);

  // Compute accelerated eta: Σ e_k · (-1)^k · (k+1)^{-s}
  // Optimize: (k+1)^{-s} = exp(-s·ln(k+1)) for real positive base
  let eta = [0, 0];
  for (let k = 0; k <= n; k++) {
    if (e[k] < 1e-18) continue; // skip negligible weights
    const sign = k % 2 === 0 ? 1 : -1;
    const logK = Math.log(k + 1);
    const mag = Math.exp(-s[0] * logK); // (k+1)^{-sigma}
    const phase = -s[1] * logK;          // -t·ln(k+1)
    const termRe = mag * Math.cos(phase);
    const termIm = mag * Math.sin(phase);
    const w = sign * e[k];
    eta[0] += w * termRe;
    eta[1] += w * termIm;
  }

  // Convert eta to zeta: zeta(s) = eta(s) / (1 - 2^{1-s})
  const log2 = Math.LN2;
  const denomMag = Math.exp((1 - s[0]) * log2);
  const denomPhase = -s[1] * log2;
  const twoTo1MinusS = [denomMag * Math.cos(denomPhase), denomMag * Math.sin(denomPhase)];
  const denom = cSub([1, 0], twoTo1MinusS);
  return cDiv(eta, denom);
}
