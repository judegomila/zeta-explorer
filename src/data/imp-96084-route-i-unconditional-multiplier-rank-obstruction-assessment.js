/**
 * Distinct nonneg log-values of the S-units generated by `logs` (each an ln p), with integer exponents in
 * [-K, K], falling in the window [0, T]. Returns { count, minGap } — the discreteness witness.
 * For a single generator the count in [0, T] saturates at floor(T / ln p) + 1 and the min gap is ln p (discrete);
 * for two multiplicatively-independent generators the count grows without bound in K and the min gap -> 0 (dense).
 */
export function sUnitLogWindow(logs, K, T) {
  const set = new Set();
  const d = logs.length;
  const rec = (i, acc) => {
    if (i === d) { if (acc >= 0 && acc <= T) set.add(Math.round(acc * 1e12) / 1e12); return; }
    for (let n = -K; n <= K; n++) rec(i + 1, acc + n * logs[i]);
  };
  rec(0, 0);
  const arr = [...set].sort((a, b) => a - b);
  let minGap = Infinity;
  for (let i = 1; i < arr.length; i++) minGap = Math.min(minGap, arr[i] - arr[i - 1]);
  return { count: arr.length, minGap };
}

