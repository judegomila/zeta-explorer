#!/usr/bin/env bash
# Auto-Improvement Engine for ZPO Explorer
# Usage: ./scripts/auto-improve.sh [start|stop|status]
#
# Invokes Claude Code CLI every 60 seconds to find and fix one issue.
# Each run makes exactly one atomic improvement, verifies the build, and commits.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
PID_FILE="$SCRIPT_DIR/.auto-improve.pid"
LOG_DIR="$SCRIPT_DIR/logs"
IMPROVEMENTS_FILE="$PROJECT_DIR/IMPROVEMENTS.md"
HEARTBEAT_FILE="$SCRIPT_DIR/.heartbeat"   # epoch-seconds written after each run; stale = stall
INTERVAL=60   # 1 minute
MAX_RUNS=1000
PUSH_EVERY=5  # push to remote after every N clean runs (imp-442)

# The prompt given to Claude Code on each iteration
IMPROVE_PROMPT='You are improving the ZPO Explorer / RH-attack project. Your task:

0. TOKEN BUDGET DISCIPLINE: the project has three HUGE monolithic files that you MUST NOT read in full unless you are editing them:
   - src/data/improvements.js (~280K tokens)
   - src/data/improvement-queue.js (~87K tokens)
   - IMPROVEMENTS.md (~60K tokens)
   Reading any of these in full blows the 40K-tokens-per-minute API tier budget.
   INSTEAD, read the pre-generated cache at scripts/queue-index.json (~4 KB) for:
   - nextImprovementId (use this for the improvements.js append id, no scan needed)
   - criticalPending / highPending / mediumPending arrays (each row has id, title, priority, category, complexity, dependsOn)
   - totalPending / totalCompleted counts
   This cache is regenerated by the engine harness BEFORE each run, so it is always fresh.

1. MANDATORY FIRST STEP: read scripts/queue-index.json and collect every pending ticket whose category is one of {proof, feature, content, meta}. IGNORE categories {bug, ux, visual, performance, accuracy} — those belong to the Haiku tier engine (scripts/auto-improve-haiku.sh) and picking them here wastes Opus quota on mechanical work. Within the Opus-eligible subset, check criticalPending first, then highPending, then mediumPending, then lowPending.

2. PRIORITY ORDER IS ABSOLUTE. Among Opus-eligible pending items, pick in strict priority order: critical > high > medium > low. Within the same priority, pick the lowest imp-NNN id (oldest first).

3. IF ANY OPUS-ELIGIBLE PENDING TICKETS EXIST: you MUST work one. Falling back to category rotation or to Haiku-tier categories is FORBIDDEN. If the highest-priority ticket is research-grade and you cannot fully close it, deliver an HONEST PARTIAL closure with a clearly-named sub-gap — this is valuable work.

4. IF ZERO Opus-eligible tickets remain: state "OPUS: no eligible tickets — exiting cleanly" and STOP. Do NOT fall through to bug/ux/visual/performance/accuracy rotation — those are Haiku-tier and the parallel Haiku engine will handle them. Do NOT invent new categories.

5. At the start of your response, state the path you are taking: "QUEUE: imp-NNN (priority X)" or "CATEGORY: <category>" — explicit commitment so the bug reappears visibly if you drift.

6. Read the relevant source files to understand the current code before changing anything.

7. Make exactly ONE small, atomic change. Do not refactor or restructure.

8. After your change, run: npm run build
   If the build fails, fix the issue before finishing.

9. Log the improvement in TWO places:

   a) Append a row to IMPROVEMENTS.md with this format:
      | # | TIMESTAMP | one-line summary | files changed |
      Use the next sequential number and current UTC timestamp.

   b) Add an entry to src/data/improvements.js by appending to the array before the closing ];
      Format:
      { id: NEXT_NUMBER, timestamp: "UTC_TIMESTAMP", category: "bug|accuracy|ux|visual|performance|content|proof", summary: "one-line summary", files: ["file1.jsx", "file2.js"], detail: "2-3 sentence description of what was changed and why" },

      TOKEN BUDGET: do NOT read src/data/improvements.js to find the next id — it is ~280K tokens. Instead:
        - Use scripts/queue-index.json nextImprovementId as the next id
        - Use the tail-append pattern: read only the LAST ~30 lines of improvements.js via offset (Read tool supports offset/limit), verify the last line is `];`, then use Edit with old_string `];` and new_string `  { id: NEXT, ... },\n];`. This uses ~1 KB of tokens instead of 280 KB.

10. Create a git commit with a descriptive message.

SYNTAX GOTCHAS (mandatory, learned from previous failures):
- DO NOT write "dg_k*/dt" or "dg_k*/dtau" inside JSDoc comments — the "*/" prematurely closes the comment. Use "dg_{k*}/dt" in comments. In JS string literals it is fine.
- DO NOT use apostrophes inside single-quoted JS strings — they close the string. Either use double-quoted strings or rewrite (e.g. "the engine\\u2019s" -> "the engine").
- The "*/" sequence anywhere inside a JSDoc comment ends the comment.

RULES:
- Never install new packages or dependencies
- Never restructure the project or rename files
- Never modify this auto-improve script or IMPROVEMENTS.md format header
- Never make more than one logical change per run
- Never delete features or pages
- Always verify the build passes before committing
- Focus on the src/ directory only
- TICKET-ID CLAIM PROTOCOL: if you ever open a new ticket in improvement-queue.js, first run `node scripts/claim-ticket-id.mjs <proposed-id>` and use the printed id instead of your proposed id. This prevents concurrent Opus/Haiku agents from creating silent id collisions (see imp-446).'

mkdir -p "$LOG_DIR"

init_improvements() {
  if [ ! -f "$IMPROVEMENTS_FILE" ]; then
    cat > "$IMPROVEMENTS_FILE" << 'EOF'
# Auto-Improvements Log

Automated improvements made by the Claude Code auto-improvement engine.

| # | Timestamp | Summary | Files Changed |
|---|-----------|---------|---------------|
EOF
  fi
}

do_start() {
  if [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
    echo "Auto-improve is already running (PID $(cat "$PID_FILE"))"
    exit 1
  fi

  init_improvements

  echo "Starting auto-improvement engine..."
  echo "  Interval: ${INTERVAL}s ($(( INTERVAL / 60 )) minutes)"
  echo "  Max runs: $MAX_RUNS"
  echo "  Logs: $LOG_DIR"
  echo "  PID file: $PID_FILE"

  # Run in background
  (
    run_count=0
    # Exponential backoff state — doubles on each rate-limit hit, resets on
    # a clean run. Bounded by BACKOFF_MAX_S so we don't sleep forever.
    backoff_s=0
    BACKOFF_MAX_S=1800  # 30 minutes
    BACKOFF_STATE_FILE="$SCRIPT_DIR/.rate-limit-backoff-state"
    rm -f "$BACKOFF_STATE_FILE"

    while [ "$run_count" -lt "$MAX_RUNS" ]; do
      run_count=$((run_count + 1))
      timestamp=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
      log_file="$LOG_DIR/run_${timestamp//[:T]/_}.log"

      echo "=== Run #$run_count at $timestamp ===" | tee "$log_file"

      # Regenerate queue-index.json BEFORE each run so the child claude
      # process can read a ~4 KB JSON cache instead of re-reading ~430 KB
      # of monolithic JS/MD files. This is the single biggest API token
      # budget fix: 100x compression on the engine's input-read step.
      node "$SCRIPT_DIR/build-queue-index.mjs" >> "$log_file" 2>&1 || true
      # Snapshot commit hash before run to detect if Claude makes a new commit
      pre_run_sha=$(git -C "$PROJECT_DIR" rev-parse HEAD 2>/dev/null || echo "")

      # Invoke Claude Code CLI (unset CLAUDECODE to avoid nested-session detection).
      # If scripts/.env exists, source it for this subshell only so
      # ANTHROPIC_API_KEY (or ANTHROPIC_AUTH_TOKEN) can be set without
      # polluting the parent shell. This lets the engine run on API billing
      # while the interactive Claude Code session keeps using the Max OAuth
      # subscription. scripts/.env is gitignored.
      if command -v claude &>/dev/null; then
        cd "$PROJECT_DIR"
        unset CLAUDECODE
        (
          if [ -f "$SCRIPT_DIR/.env" ]; then
            set -a
            . "$SCRIPT_DIR/.env"
            set +a
          fi
          claude --print --dangerously-skip-permissions "$IMPROVE_PROMPT" \
            >> "$log_file" 2>&1
        ) || true
      else
        echo "ERROR: 'claude' CLI not found in PATH" >> "$log_file"
        echo "Claude CLI not found. Install it or add to PATH."
        break
      fi

      echo "=== Run #$run_count complete ===" >> "$log_file"
      echo "Run #$run_count complete. Log: $log_file"
      # Update heartbeat so stall detection can verify the loop is still alive.
      date +%s > "$HEARTBEAT_FILE"

      # ── Dev-server liveness check (imp-313) ──────────────────────────────
      # After each run, confirm the dev server on :3002 still responds HTTP 200.
      # A bad improvement can break the server silently; catching it here stops
      # the engine from compounding the damage.
      DEV_SERVER_URL="http://localhost:3002"
      http_status=$(curl -sfo /dev/null -w "%{http_code}" --connect-timeout 5 "$DEV_SERVER_URL" 2>/dev/null || echo "000")
      if [ "$http_status" = "200" ]; then
        echo "DEV-SERVER OK: $DEV_SERVER_URL returned 200" | tee -a "$log_file"
      else
        echo "DEV-SERVER FAIL: $DEV_SERVER_URL returned $http_status -- halting engine to prevent cascading damage" | tee -a "$log_file"
        echo "RUN #$run_count ($timestamp): dev-server returned $http_status -- engine halted" >> "$SCRIPT_DIR/dev-server-failures.log"
        break
      fi

      # ── Post-commit status-flip verification ──────────────────────────────
      # Parse the last commit message for an imp-NNN id and confirm that
      # ticket is now marked completed in the queue. Any drift is appended
      # to scripts/status-flip-drift.log for operator review.
      post_run_sha=$(git -C "$PROJECT_DIR" rev-parse HEAD 2>/dev/null || echo "")
      if [ -n "$pre_run_sha" ] && [ "$post_run_sha" != "$pre_run_sha" ]; then
        last_commit_msg=$(git -C "$PROJECT_DIR" log -1 --pretty=%s 2>/dev/null || echo "")
        commit_imp=$(echo "$last_commit_msg" | grep -oE 'imp-[0-9]+' | head -1)
        if [ -n "$commit_imp" ]; then
          flip_status=$(python3 -c "
import re
text = open('$PROJECT_DIR/src/data/improvement-queue.js').read()
m = re.search(r\"id: '$commit_imp'.*?status: '(\\w+)'\", text, re.DOTALL)
print(m.group(1) if m else 'not-found')" 2>/dev/null || echo "error")
          if [ "$flip_status" = "completed" ]; then
            echo "STATUS-FLIP VERIFIED: $commit_imp -> completed" | tee -a "$log_file"
          else
            drift_msg="RUN #$run_count ($timestamp): $commit_imp committed (queue-status=$flip_status) but NOT flipped to completed. Commit: $last_commit_msg"
            echo "STATUS-FLIP WARN: $drift_msg" | tee -a "$log_file"
            echo "$drift_msg" >> "$SCRIPT_DIR/status-flip-drift.log"
          fi
        fi
      fi

      # ── Rate-limit detection + exponential backoff ──────────────────────
      # Scan this run's log for any of the known rate-limit / API error
      # patterns. On detection: double the backoff sleep, write a sentinel
      # file with the current state (so the monitor cron and a human
      # operator can see the engine is backing off), and record that the
      # current ticket remains pending (the engine's prompt only flips
      # pending → completed after a successful commit, so mid-run failures
      # naturally leave the ticket in the queue — the sentinel just makes
      # that state explicit and visible).
      if grep -qiE "rate.?limit|429|quota.?exceed|ConnectionRefused|API Error|too many requests" "$log_file"; then
        if [ "$backoff_s" -eq 0 ]; then
          backoff_s=60
        else
          backoff_s=$((backoff_s * 2))
        fi
        if [ "$backoff_s" -gt "$BACKOFF_MAX_S" ]; then
          backoff_s=$BACKOFF_MAX_S
        fi
        error_line=$(grep -iE "rate.?limit|429|quota.?exceed|ConnectionRefused|API Error|too many requests" "$log_file" | head -1)
        cat > "$BACKOFF_STATE_FILE" << EOF
{
  "detected_at": "$timestamp",
  "run_number": $run_count,
  "log_file": "$log_file",
  "error_line": $(echo "$error_line" | python3 -c "import sys, json; print(json.dumps(sys.stdin.read().strip()))"),
  "current_backoff_seconds": $backoff_s,
  "note": "Any ticket started by this run remains status:pending in improvement-queue.js — the prompt only flips status after a successful commit, so mid-run failures naturally queue the in-flight work for the next clean run.",
  "resume_strategy": "Sleep backoff_s seconds then retry. If the next run also hits the pattern, backoff doubles. A clean run resets backoff to 0."
}
EOF
        echo "RATE LIMIT DETECTED on run #$run_count. Backing off ${backoff_s}s (sentinel: $BACKOFF_STATE_FILE)" | tee -a "$log_file"
      else
        # Clean run — reset backoff and clear sentinel.
        if [ -f "$BACKOFF_STATE_FILE" ]; then
          rm -f "$BACKOFF_STATE_FILE"
          echo "Clean run — rate-limit sentinel cleared, backoff reset." | tee -a "$log_file"
        fi
        backoff_s=0
      fi

      # ── Auto-push every N runs ────────────────────────────────────────
      # Bound the local-only commit window so a laptop crash or network
      # partition cannot strand more than PUSH_EVERY runs of commits.
      # Only push when there are unpushed commits to avoid noisy log lines.
      if [ "$((run_count % PUSH_EVERY))" -eq 0 ]; then
        unpushed=$(git -C "$PROJECT_DIR" log --oneline @{u}..HEAD 2>/dev/null | wc -l | tr -d ' ')
        if [ "${unpushed:-0}" -gt 0 ]; then
          echo "AUTO-PUSH: $unpushed unpushed commit(s) — pushing (run #$run_count, every ${PUSH_EVERY} runs)..." | tee -a "$log_file"
          git -C "$PROJECT_DIR" push >> "$log_file" 2>&1 \
            && echo "AUTO-PUSH: success" | tee -a "$log_file" \
            || echo "AUTO-PUSH: push failed (non-fatal; will retry at next multiple of $PUSH_EVERY)" | tee -a "$log_file"
        else
          echo "AUTO-PUSH: nothing new to push at run #$run_count" | tee -a "$log_file"
        fi
      fi

      # Wait for next interval, plus the exponential backoff if any.
      if [ "$run_count" -lt "$MAX_RUNS" ]; then
        sleep_total=$((INTERVAL + backoff_s))
        sleep "$sleep_total"
      fi
    done

    echo "Auto-improve completed $run_count runs. Stopping."
    rm -f "$PID_FILE"
  ) &

  local bg_pid=$!
  echo "$bg_pid" > "$PID_FILE"
  disown
  echo "Auto-improve started in background (PID $bg_pid)"
}

do_stop() {
  if [ ! -f "$PID_FILE" ]; then
    echo "Auto-improve is not running (no PID file)"
    exit 0
  fi

  pid=$(cat "$PID_FILE")
  if kill -0 "$pid" 2>/dev/null; then
    echo "Stopping auto-improve (PID $pid)..."
    kill "$pid" 2>/dev/null || true
    # Also kill any child claude processes
    pkill -P "$pid" 2>/dev/null || true
    rm -f "$PID_FILE"
    echo "Stopped."
  else
    echo "Process $pid not found. Cleaning up PID file."
    rm -f "$PID_FILE"
  fi
}

do_status() {
  stall_detected=0
  if [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
    pid=$(cat "$PID_FILE")
    echo "Auto-improve is RUNNING (PID $pid)"
    # Heartbeat stall detection: fail (exit 1) if no new run within 2 intervals.
    if [ -f "$HEARTBEAT_FILE" ]; then
      last_beat=$(stat -f %m "$HEARTBEAT_FILE" 2>/dev/null || echo 0)
      beat_age=$(( $(date +%s) - last_beat ))
      stall_threshold=$(( INTERVAL * 2 ))
      if [ "$beat_age" -gt "$stall_threshold" ]; then
        echo "  STALL DETECTED: heartbeat ${beat_age}s stale (threshold ${stall_threshold}s = 2 ticks)"
        stall_detected=1
      else
        echo "  Heartbeat OK: ${beat_age}s ago"
      fi
    else
      echo "  Heartbeat: no heartbeat yet (engine may still be starting up)"
    fi
    # Count completed runs
    run_count=$(ls "$LOG_DIR"/run_*.log 2>/dev/null | wc -l | tr -d ' ')
    echo "  Completed runs: $run_count"
    # Show latest log
    latest=$(ls -t "$LOG_DIR"/run_*.log 2>/dev/null | head -1)
    if [ -n "$latest" ]; then
      echo "  Latest log: $latest"
      echo "  Last 3 lines:"
      tail -3 "$latest" | sed 's/^/    /'
    fi
  else
    echo "Auto-improve is NOT running"
    if [ -f "$PID_FILE" ]; then
      echo "  (stale PID file found, cleaning up)"
      rm -f "$PID_FILE"
    fi
    run_count=$(ls "$LOG_DIR"/run_*.log 2>/dev/null | wc -l | tr -d ' ')
    echo "  Total completed runs: $run_count"
  fi

  # Show improvements count
  if [ -f "$IMPROVEMENTS_FILE" ]; then
    imp_count=$(grep -c '^|[^|]*|[^|]*|[^|]*|[^|]*|$' "$IMPROVEMENTS_FILE" 2>/dev/null || echo 0)
    imp_count=$((imp_count - 1))  # subtract header
    [ "$imp_count" -lt 0 ] && imp_count=0
    echo "  Improvements logged: $imp_count"
  fi
  return "$stall_detected"
}

case "${1:-}" in
  start)  do_start ;;
  stop)   do_stop ;;
  status) do_status ;;
  *)
    echo "Usage: $0 {start|stop|status}"
    echo ""
    echo "  start   - Start the auto-improvement loop (runs every 60 sec)"
    echo "  stop    - Stop the running loop"
    echo "  status  - Check if running and show stats"
    exit 1
    ;;
esac
