#!/usr/bin/env node
// scripts/rotate-improvements.mjs
//
// Closes imp-1020: archive entries older than 90 days from
// src/data/improvements.js into a sibling src/data/improvements-archive.js
// so the bundled improvements log stops growing without bound.
//
// The script is DRY-RUN by default. It only writes anything when invoked
// with --execute. This is intentional: improvements.js is one of the largest
// chunks in the bundle and the consumer pages (ImprovementsPage.jsx,
// MetaAccelerationPage.jsx) dynamic-import it at runtime, so a botched
// rotation would silently truncate the visible improvement log. The
// dry-run dump lets an operator see exactly which entries would move
// before committing to the split.
//
// Usage:
//   node scripts/rotate-improvements.mjs                        # dry-run (default)
//   node scripts/rotate-improvements.mjs --execute              # perform rotation
//   node scripts/rotate-improvements.mjs --max-age-days 60      # custom cutoff
//   node scripts/rotate-improvements.mjs --execute --quiet      # silence the diff dump
//
// Atomicity: when --execute is set, the script writes both output files to
// sibling .tmp paths first, then renames them into place in two
// fs.renameSync calls. Rename on a single POSIX filesystem is atomic per
// path, so a crash between the two renames can leave improvements.js
// shrunk without the matching archive — to keep the pair consistent we
// write the archive FIRST and the trimmed live file SECOND. If the second
// rename fails the archive will contain a superset of what is in the live
// file (no data lost), and a subsequent rerun is safe because the script
// is idempotent: entries already in the archive are merged-by-id, not
// duplicated.
//
// After a successful --execute, the script invokes
// `node scripts/build-queue-index.mjs` so that
// scripts/queue-index.json#improvementsTotal and #nextImprovementId stay
// consistent with the trimmed live file the engine reads.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PROJECT_ROOT = path.resolve(__dirname, '..');
const LIVE_FILE = path.join(PROJECT_ROOT, 'src/data/improvements.js');
const ARCHIVE_FILE = path.join(PROJECT_ROOT, 'src/data/improvements-archive.js');
const BUILD_INDEX_SCRIPT = path.join(PROJECT_ROOT, 'scripts/build-queue-index.mjs');

const argv = process.argv.slice(2);
const EXECUTE = argv.includes('--execute');
const QUIET = argv.includes('--quiet');
const ageIdx = argv.indexOf('--max-age-days');
const MAX_AGE_DAYS = ageIdx >= 0 ? Number(argv[ageIdx + 1]) : 90;
if (!Number.isFinite(MAX_AGE_DAYS) || MAX_AGE_DAYS <= 0) {
  console.error(`rotate-improvements: --max-age-days must be a positive number, got ${argv[ageIdx + 1]}`);
  process.exit(2);
}
const MAX_AGE_MS = MAX_AGE_DAYS * 24 * 60 * 60 * 1000;
const NOW = Date.now();

function fail(code, msg) {
  console.error(`rotate-improvements: ${msg}`);
  process.exit(code);
}

// ── Parse improvements.js by line ─────────────────────────────────────────
//
// The file is auto-generated by scripts/auto-improve.sh with the strict
// convention "one entry per line, surrounded by `export const improvements = [`
// and `];`". We rely on that convention so we can avoid loading and re-
// emitting a 280K-token JS AST. If the file ever violates the convention
// (multi-line entries, comments between entries, etc.), the regex below
// will fail to match and the script will refuse to rotate.

// Two on-disk shapes coexist in improvements.js (history of two engine eras):
//   modern: { id: N, timestamp: "ISO8601", category: "...", summary: "...", ... }
//   legacy: { id: N, text: "...", category: "...", date: "YYYY-MM-DD", auto: true }
// We extract the date from whichever field is present.
const ID_RE = /^\s*\{\s*id:\s*(\d+)\b/;
const TIMESTAMP_RE = /\btimestamp:\s*"([^"]+)"/;
const DATE_RE = /\bdate:\s*"([^"]+)"/;

function extractEntry(line, lineNumberForError) {
  const idM = ID_RE.exec(line);
  if (!idM) return null;
  const id = parseInt(idM[1], 10);
  const tsM = TIMESTAMP_RE.exec(line) ?? DATE_RE.exec(line);
  if (!tsM) {
    fail(
      2,
      `line ${lineNumberForError} has id ${id} but neither timestamp: nor date: field; refusing to rotate: ${line.slice(0, 120)}`,
    );
  }
  const tsMs = Date.parse(tsM[1]);
  if (!Number.isFinite(tsMs)) {
    fail(2, `line ${lineNumberForError}: unparseable date ${JSON.stringify(tsM[1])}`);
  }
  return { id, tsMs, line };
}

function parseLiveFile(text) {
  const lines = text.split('\n');
  const openIdx = lines.findIndex((l) => /^export const improvements\s*=\s*\[/.test(l));
  const closeIdx = lines.findIndex((l, i) => i > openIdx && /^\];\s*$/.test(l));
  if (openIdx < 0) fail(2, 'could not find `export const improvements = [` header line');
  if (closeIdx < 0) fail(2, 'could not find closing `];` line');

  const entryLines = [];
  for (let i = openIdx + 1; i < closeIdx; i++) {
    const line = lines[i];
    const trimmed = line.trim();
    if (trimmed === '') continue;
    // Decorative `// ── Wave N` separators between entries are not data —
    // they stay in the live file as-is, so we skip them during data parse.
    if (trimmed.startsWith('//')) continue;
    const entry = extractEntry(line, i + 1);
    if (!entry) {
      fail(
        2,
        `line ${i + 1} did not match the expected single-line entry shape; refusing to rotate: ${line.slice(0, 120)}`,
      );
    }
    entry.sourceLineIdx = i;
    entryLines.push(entry);
  }
  return { lines, openIdx, closeIdx, entryLines };
}

// Existing archive (may not exist on first rotation).
function parseArchiveFile() {
  if (!fs.existsSync(ARCHIVE_FILE)) return { existing: [], headerLines: null };
  const text = fs.readFileSync(ARCHIVE_FILE, 'utf8');
  const lines = text.split('\n');
  const openIdx = lines.findIndex((l) => /^export const improvementsArchive\s*=\s*\[/.test(l));
  const closeIdx = lines.findIndex((l, i) => i > openIdx && /^\];\s*$/.test(l));
  if (openIdx < 0 || closeIdx < 0) {
    fail(2, `existing ${path.relative(PROJECT_ROOT, ARCHIVE_FILE)} does not match the expected shape; refusing to overwrite`);
  }
  const existing = [];
  for (let i = openIdx + 1; i < closeIdx; i++) {
    const line = lines[i];
    if (line.trim() === '') continue;
    const entry = extractEntry(line, i + 1);
    if (!entry) fail(2, `archive line ${i + 1} not in expected entry shape: ${line.slice(0, 120)}`);
    existing.push(entry);
  }
  return { existing, headerLines: lines.slice(0, openIdx + 1).join('\n') };
}

// ── Main ──────────────────────────────────────────────────────────────────

function main() {
  if (!fs.existsSync(LIVE_FILE)) fail(2, `${path.relative(PROJECT_ROOT, LIVE_FILE)} missing`);
  const liveText = fs.readFileSync(LIVE_FILE, 'utf8');
  const { lines, closeIdx, entryLines } = parseLiveFile(liveText);

  const cutoffMs = NOW - MAX_AGE_MS;
  const keep = [];
  const archive = [];
  for (const e of entryLines) {
    if (e.tsMs < cutoffMs) archive.push(e);
    else keep.push(e);
  }

  console.log(`rotate-improvements: cutoff = ${new Date(cutoffMs).toISOString()} (max-age-days=${MAX_AGE_DAYS})`);
  console.log(`  live entries     : ${entryLines.length}`);
  console.log(`  would keep       : ${keep.length}`);
  console.log(`  would archive    : ${archive.length}`);

  if (archive.length === 0) {
    console.log('rotate-improvements: nothing to archive — exiting cleanly.');
    return;
  }

  if (!QUIET) {
    const firstFew = archive.slice(0, 3).map((e) => `    id ${e.id} ${new Date(e.tsMs).toISOString()}`);
    const lastFew = archive.slice(-3).map((e) => `    id ${e.id} ${new Date(e.tsMs).toISOString()}`);
    console.log('  oldest to archive:');
    firstFew.forEach((l) => console.log(l));
    if (archive.length > 6) console.log('    ...');
    console.log('  newest to archive:');
    lastFew.forEach((l) => console.log(l));
  }

  if (!EXECUTE) {
    console.log('\nrotate-improvements: DRY RUN (pass --execute to perform rotation).');
    return;
  }

  // Merge with existing archive, dedupe by id (newer entry wins on conflict).
  const { existing, headerLines: existingArchiveHeader } = parseArchiveFile();
  const merged = new Map();
  for (const e of existing) merged.set(e.id, e);
  for (const e of archive) merged.set(e.id, e);
  const mergedSorted = [...merged.values()].sort((a, b) => a.id - b.id);

  const archiveHeader = existingArchiveHeader ?? [
    '// Auto-generated by scripts/rotate-improvements.mjs — do not edit manually',
    `// Entries older than ${MAX_AGE_DAYS} days, rotated out of improvements.js.`,
    '// Schema is identical to src/data/improvements.js. To read the full historical',
    '// log, import `improvementsArchive` from this file and concatenate it with',
    '// `improvements` from src/data/improvements.js.',
    'export const improvementsArchive = [',
  ].join('\n');

  const archiveBody = mergedSorted.map((e) => e.line).join('\n');
  const archiveOut = `${archiveHeader}\n${archiveBody}\n];\n`;

  // Build the trimmed live file by deleting the archive-bound entry lines
  // in place from the original line array. This preserves decorative
  // `// ── Wave N` separators, blank lines, and the surrounding header /
  // trailer text byte-for-byte, so the only diff is the removed entries.
  const archiveLineIdxSet = new Set(archive.map((e) => e.sourceLineIdx));
  const liveLines = [];
  for (let i = 0; i < lines.length; i++) {
    if (i <= closeIdx && archiveLineIdxSet.has(i)) continue;
    liveLines.push(lines[i]);
  }
  const liveOut = liveLines.join('\n');

  const archiveTmp = `${ARCHIVE_FILE}.tmp`;
  const liveTmp = `${LIVE_FILE}.tmp`;
  fs.writeFileSync(archiveTmp, archiveOut);
  fs.writeFileSync(liveTmp, liveOut);
  // Write archive first: if the second rename fails, no entries are lost.
  fs.renameSync(archiveTmp, ARCHIVE_FILE);
  fs.renameSync(liveTmp, LIVE_FILE);

  console.log(`\nrotate-improvements: wrote ${path.relative(PROJECT_ROOT, ARCHIVE_FILE)} (${mergedSorted.length} entries)`);
  console.log(`rotate-improvements: trimmed ${path.relative(PROJECT_ROOT, LIVE_FILE)} (${keep.length} entries kept)`);

  // Regenerate scripts/queue-index.json so improvementsTotal / nextImprovementId
  // stay consistent with the trimmed live file the engine reads.
  try {
    execFileSync('node', [BUILD_INDEX_SCRIPT], { stdio: QUIET ? 'ignore' : 'inherit' });
  } catch (e) {
    fail(1, `wrote rotated files but failed to regenerate queue-index.json: ${e.message}`);
  }
}

main();
